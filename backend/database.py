def get_contract_id_from_signer(signer_id):
    try:
        signer_id = int(signer_id)
    except (ValueError, TypeError):
        raise ValueError(
            f"Invalid signer_id: {signer_id}. It must be an integer."
        )

    result = execute_query("""
        SELECT contract_id
        FROM contract_signers
        WHERE signer_id = %s;
    """, (signer_id,), fetchone=True)

    if result is None:
        raise ValueError(f"No contract found for signer_id {signer_id}")

    return result[0]


