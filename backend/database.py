def claim_due_signers(limit=100, lease_seconds=120):
    with closing(get_connection()) as conn:
        with conn:
            with conn.cursor() as cursor:
                # Define the SQL query
                query = """
                    WITH due_signers AS (

                        SELECT cs.signer_id, cs.next_check_at AS check_at

                        FROM contract_signers cs

                        WHERE cs.status IN (
                            'queued',
                            'awaiting_email',
                            'awaiting_eid_approval'
                        )

                        AND (
                            cs.next_check_at IS NULL
                            OR cs.next_check_at <= NOW()
                        )

                        AND (
                            cs.ordering_matters = FALSE
                            OR NOT EXISTS (
                                SELECT 1
                                FROM contract_signers previous
                                WHERE previous.contract_id = cs.contract_id
                                AND previous.position < cs.position
                                AND previous.status NOT IN ('signed', 'completed')
                            )
                        )

                        ORDER BY cs.next_check_at ASC NULLS FIRST
                        LIMIT %s
                        FOR UPDATE OF cs SKIP LOCKED
                    ),

                    due_contracts AS (

                        SELECT
                            c.contract_id,
                            c.signits_next_check_at AS check_at

                        FROM contracts c

                        WHERE c.status NOT IN ('completed', 'declined', 'failed')
                          AND (
                              c.signits_next_check_at IS NULL
                              OR c.signits_next_check_at <= NOW()
                          )

                        ORDER BY c.signits_next_check_at ASC NULLS FIRST
                        LIMIT %s
                        FOR UPDATE OF c SKIP LOCKED
                    ),

                    ranked_items AS (

                        SELECT *
                        FROM (
                            SELECT
                                'signer' AS item_type,
                                signer_id AS item_id,
                                check_at
                            FROM due_signers

                            UNION ALL

                            SELECT
                                'contract' AS item_type,
                                contract_id AS item_id,
                                check_at
                            FROM due_contracts
                        ) items

                        ORDER BY check_at ASC NULLS FIRST
                        LIMIT %s
                    ),

                    claimed_signers AS (

                        UPDATE contract_signers cs

                        SET next_check_at =
                            NOW() + (%s * INTERVAL '1 second'),
                            updated_at = NOW()

                        FROM ranked_items r

                        WHERE r.item_type = 'signer'
                          AND cs.signer_id = r.item_id

                        RETURNING
                            'signer' AS item_type,
                            cs.signer_id AS item_id
                    ),

                    claimed_contracts AS (

                        UPDATE contracts c

                        SET signits_next_check_at =
                            NOW() + (%s * INTERVAL '1 second'),
                            updated_at = NOW()

                        FROM ranked_items r

                        WHERE r.item_type = 'contract'
                          AND c.contract_id = r.item_id

                        RETURNING
                            'contract' AS item_type,
                            c.contract_id AS item_id
                    )

                    SELECT item_type, item_id
                    FROM claimed_signers

                    UNION ALL

                    SELECT item_type, item_id
                    FROM claimed_contracts;
                """
                # Construct the query for psql testing
                formatted_query = query % (
                    limit,
                    limit,
                    limit,
                    lease_seconds,
                    lease_seconds
                )
                print("\nQuery for psql:")
                #print(formatted_query)

                # Execute the query
                cursor.execute(query, (
                    limit,
                    limit,
                    limit,
                    lease_seconds,
                    lease_seconds
                ))

                # Fetch and return the results
                return [
                    (row[0], row[1])
                    for row in cursor.fetchall()
                ]


