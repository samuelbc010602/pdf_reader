def init_db():
    delete_first = True

    with closing(get_connection()) as conn:
        with conn:
            with conn.cursor() as cursor:

                # Only enable this when deliberately resetting development data.
                if delete_first:
                    cursor.execute("DROP TABLE IF EXISTS contracts CASCADE;")
                    cursor.execute("DROP TABLE IF EXISTS contract_signers CASCADE;")
                    cursor.execute("DROP TABLE IF EXISTS users CASCADE;")
                    
                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS users (
                        user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        password_hash TEXT NOT NULL,
                        name TEXT,
                        mail TEXT
                    );
                """)

                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS contracts (
                        contract_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

                        user_id INT NOT NULL
                            REFERENCES users(user_id)
                            ON DELETE CASCADE,

                        title TEXT NOT NULL,
                        sender_name TEXT NOT NULL,
                        sender_mail TEXT NOT NULL,

                        sign_method VARCHAR(100) NOT NULL,
                        ordering_matters BOOLEAN NOT NULL DEFAULT FALSE,
                        pdf_path TEXT NOT NULL,

                        status VARCHAR(50) NOT NULL DEFAULT 'pending',

                        signits_contract_id TEXT DEFAULT 'NO_ID',
                        past_contracts TEXT[] DEFAULT '{}',

                        signSamePdf BOOLEAN NOT NULL DEFAULT FALSE,
                        waitForPdfApproval BOOLEAN NOT NULL DEFAULT TRUE,

                        -- Direct SIGNITS polling
                        signits_next_check_at TIMESTAMPTZ,
                        signits_last_checked_at TIMESTAMPTZ,
                        signits_error TEXT,

                        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
                    );
                """)
                # --------------------------------------------------
                # CONTRACT SIGNERS
                # --------------------------------------------------

                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS contract_signers (
                        signer_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

                        contract_id BIGINT NOT NULL
                            REFERENCES contracts(contract_id)
                            ON DELETE CASCADE,

                        position INT NOT NULL,

                        signer_name TEXT NOT NULL,
                        signer_mail TEXT NOT NULL,

                        mail_reference TEXT NOT NULL UNIQUE,

                        status VARCHAR(50) NOT NULL DEFAULT 'queued',
                        ordering_matters BOOLEAN NOT NULL DEFAULT FALSE,

                        mail_sent_at TIMESTAMPTZ,

                        received_pdf_path TEXT,
                        mail_message_id TEXT,

                        signits_contract_id TEXT DEFAULT 'NO_ID',

                        signed_pdf_path TEXT,
                        signits_signed BOOLEAN NOT NULL DEFAULT FALSE,
                        pdf_signed BOOLEAN NOT NULL DEFAULT FALSE,

                        next_check_at TIMESTAMPTZ,
                        last_checked_at TIMESTAMPTZ,
                        error TEXT,

                        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

                        UNIQUE(contract_id, position)
                    );
                """)
                
                cursor.execute("""        
                    CREATE TABLE contract_access_tokens (
                    id SERIAL PRIMARY KEY,
                    contract_id INTEGER NOT NULL
                        REFERENCES contracts(contract_id) ON DELETE CASCADE,

                    token_hash TEXT NOT NULL UNIQUE,

                    expires_at TIMESTAMPTZ NOT NULL,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                    used_at TIMESTAMPTZ,

                    access_email TEXT NOT NULL
                );

                CREATE INDEX idx_contract_access_tokens_hash
                ON contract_access_tokens(token_hash);
                    """)

                # --------------------------------------------------
                # INDEXES
                # --------------------------------------------------

                cursor.execute("""
                    CREATE INDEX IF NOT EXISTS idx_contracts_user
                    ON contracts(user_id, created_at DESC);
                """)

                cursor.execute("""
                    CREATE INDEX IF NOT EXISTS idx_signers_contract
                    ON contract_signers(contract_id, position);
                """)

                cursor.execute("""
                    CREATE INDEX IF NOT EXISTS idx_signers_due
                    ON contract_signers(next_check_at)
                    WHERE status IN (
                        'awaiting_mail',
                        'awaiting_eid_approval'
                    );
                """)

                cursor.execute("""
                    CREATE INDEX IF NOT EXISTS idx_signers_parallel_queue
                    ON contract_signers(next_check_at)
                    WHERE ordering_matters = FALSE
                      AND status IN (
                          'awaiting_mail',
                          'awaiting_eid_approval'
                      );
                """)

                cursor.execute("""
                    CREATE INDEX IF NOT EXISTS idx_signers_sequential_queue
                    ON contract_signers(contract_id, position)
                    WHERE ordering_matters = TRUE
                      AND status IN (
                          'awaiting_mail',
                          'awaiting_eid_approval'
                      );
                """)

                cursor.execute("""
                    CREATE INDEX IF NOT EXISTS idx_contracts_signits_due
                    ON contracts(signits_next_check_at)
                    WHERE signits_contract_id IS NOT NULL
                      AND signits_contract_id <> 'NO_ID'
                      AND signits_next_check_at IS NOT NULL;
                """)
    print("Database initialized.")



