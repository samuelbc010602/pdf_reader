def refresh_contract_status(contract_id):
    with closing(get_connection()) as conn:
        with conn:
            with conn.cursor() as cursor:

                cursor.execute("""
                    SELECT
                        COUNT(*),
                        COUNT(*) FILTER (
                            WHERE status = 'completed'
                        ),
                        COUNT(*) FILTER (
                            WHERE status = 'declined'
                        ),
                        COUNT(*) FILTER (
                            WHERE status = 'failed'
                        )
                    FROM contract_signers
                    WHERE contract_id = %s;
                """, (contract_id,))

                total, completed, declined, failed = cursor.fetchone()

                if total == 0:
                    status = "pending"

                elif completed == total:
                    status = "completed"

                elif failed:
                    status = "failed"

                elif declined:
                    status = "declined"

                else:
                    status = "in_progress"

                cursor.execute("""
                    UPDATE contracts
                    SET status = %s,
                        updated_at = NOW()
                    WHERE contract_id = %s;
                """, (status, contract_id))


