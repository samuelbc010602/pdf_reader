def update_past_contracts(
    contract_id,
    signits_contract_id,
    add_to_past_contracts=False
):
    execute_query("""
        UPDATE contracts
        SET past_contracts = CASE
                WHEN %s THEN array_append(
                    COALESCE(past_contracts, ARRAY[]::text[]),
                    %s
                )
                WHEN signits_contract_id IS NOT NULL
                     AND signits_contract_id != 'NO_ID'
                THEN array_append(
                    COALESCE(past_contracts, ARRAY[]::text[]),
                    signits_contract_id
                )
                ELSE COALESCE(past_contracts, ARRAY[]::text[])
            END,
            signits_contract_id = %s,
            updated_at = NOW()
        WHERE contract_id = %s;
    """, (
        add_to_past_contracts,
        signits_contract_id,
        signits_contract_id,
        contract_id,
    ))
    
