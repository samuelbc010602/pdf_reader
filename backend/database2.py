def get_next_ordered_signer(contract_id):

    with closing(get_connection()) as conn:
        with conn.cursor() as cursor:

            cursor.execute("""
                SELECT signer_id, status
                FROM contract_signers
                WHERE contract_id = %s
                ORDER BY position ASC;
            """, (contract_id,))

            signers = cursor.fetchall()

    for signer_id, status in signers:

        if status in ("failed", "declined"):
            return None

        if status == "completed":
            continue

        if status == "queued":
            return signer_id

        return None

    return None



