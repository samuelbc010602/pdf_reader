def claim_due_signers(limit=100, lease_seconds=120):

    with closing(get_connection()) as conn:
        with conn:
            with conn.cursor() as cursor:

                cursor.execute("""
                    WITH due_signers AS (
                        SELECT cs.signer_id
                        FROM contract_signers cs

                        WHERE cs.status IN (
                            'awaiting_email',
                            'awaiting_eid_approval'
                        )
                        AND cs.next_check_at <= NOW()

                        AND (
                            cs.ordering_matters = FALSE

                            OR (
                                cs.ordering_matters = TRUE

                                AND NOT EXISTS (
                                    SELECT 1
                                    FROM contract_signers previous
                                    WHERE previous.contract_id = cs.contract_id
                                      AND previous.position < cs.position
                                      AND previous.status <> 'completed'
                                )
                            )
                        )

                        ORDER BY cs.next_check_at ASC
                        LIMIT %s
                        FOR UPDATE OF cs SKIP LOCKED
                    )

                    UPDATE contract_signers cs

                    SET next_check_at =
                        NOW() + (%s * INTERVAL '1 second'),
                        updated_at = NOW()

                    FROM due_signers d

                    WHERE cs.signer_id = d.signer_id

                    RETURNING cs.signer_id;
                """, (limit, lease_seconds))

                return [row[0] for row in cursor.fetchall()]

