def update_signer(signer_id, **fields):

    allowed_fields = {
        "status",
        "email_sent_at",
        "received_pdf_path",
        "gmail_message_id",
        "signits_contract_id",
        "signed_pdf_path",
        "next_check_at",
        "last_checked_at",
        "error"
    }
    
    print("in update_signer for signer_id",signer_id)

    if not fields:
        return

    if not set(fields).issubset(allowed_fields):
        raise ValueError("Invalid signer update field")

    assignments = ", ".join(
        f"{field} = %s" for field in fields
    )

    values = list(fields.values())
    values.append(signer_id)

    with closing(get_connection()) as conn:
        with conn:
            with conn.cursor() as cursor:

                cursor.execute(
                    f"""
                    UPDATE contract_signers
                    SET {assignments},
                        updated_at = NOW()
                    WHERE signer_id = %s;
                    """,
                    values
                )
    print("updated contract_signers with", values)


