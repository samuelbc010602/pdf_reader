def create_contract_in_db(
    user_id,
    title,
    username,
    mail,
    sign_method,
    ordering_matters,
    pdf_path,
    signers,
    signSamePdf,
    waitForPdfApproval
):
    """
    Creates one contract and all its signer records.

    Returns:
        contract_id, signer_ids
    """

    with closing(get_connection()) as conn:
        with conn:
            with conn.cursor() as cursor:

                cursor.execute("""
                    INSERT INTO contracts (
                        user_id,
                        title,
                        username,
                        mail,
                        sign_method,
                        ordering_matters,
                        pdf_path,
                        signSamePdf,
                        waitForPdfApproval,
                        status
                    )
                    VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, 'pending')
                    RETURNING contract_id;
                """, (
                    user_id,
                    title,
                    username,
                    mail,
                    sign_method,
                    ordering_matters,
                    str(pdf_path),
                    signSamePdf,
                    waitForPdfApproval
                ))

                contract_id = cursor.fetchone()[0]

                signer_ids = []

                for position, signer in enumerate(signers, start=1):

                    import uuid

                    email_reference = uuid.uuid4().hex

                    cursor.execute("""
                        INSERT INTO contract_signers (
                            contract_id,
                            position,
                            name,
                            email,
                            email_reference,
                            ordering_matters
                        )
                        VALUES (%s, %s, %s, %s, %s, %s)
                        RETURNING signer_id;
                    """, (
                        contract_id,
                        position,
                        signer["name"],
                        signer["email"],
                        email_reference,
                        ordering_matters
                    ))

                    signer_ids.append(cursor.fetchone()[0])

    return contract_id, signer_ids


