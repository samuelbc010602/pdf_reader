def get_signer(signer_id):
    with closing(get_connection()) as conn:
        with conn.cursor(cursor_factory=RealDictCursor) as cursor:

            cursor.execute("""
                SELECT
                    s.signer_id,
                    s.contract_id,
                    s.position,
                    s.signer_name,
                    s.signer_mail,
                    s.mail_reference,
                    s.status,
                    s.received_pdf_path,
                    s.mail_message_id,
                    s.signits_contract_id,
                    s.signed_pdf_path,
                    s.next_check_at,
                    s.last_checked_at,
                    s.error,

                    c.title,
                    c.sender_name,
                    c.sender_mail,
                    c.sign_method,
                    c.ordering_matters,
                    c.pdf_path,
                    c.signSamePdf,
                    c.waitForPdfApproval,
                    c.signits_contract_id AS contract_signits_contract_id

                FROM contract_signers s
                JOIN contracts c
                    ON c.contract_id = s.contract_id

                WHERE s.signer_id = %s;
            """, (signer_id,))

            return cursor.fetchone()

     


